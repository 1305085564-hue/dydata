import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { parse } from 'dotenv';
import { chromium, expect } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';

const baseUrl = process.env.AI_GOVERNANCE_PAGE_URL;
const dbUrl = process.env.AI_GOVERNANCE_TEST_URL;
for (const url of [baseUrl, dbUrl]) assert.match(url ?? '', /^http:\/\/(?:127\.0\.0\.1|localhost):\d+$/);
const env = parse(readFileSync('.env.ai-test.local'));
const db = createClient(dbUrl, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
const providerId = randomUUID();
const keyIds = [randomUUID(), randomUUID(), randomUUID()];
const modelIds = [`governance-browser-a-${randomUUID()}`, `governance-browser-b-${randomUUID()}`];
const browser = await chromium.launch({ headless: true });
let pageErrors = [];
try {
  assert.equal((await db.from('ai_providers').insert({ id: providerId, name: '渠道治理本地页面验收', base_url: 'https://unused.invalid/v1', priority: 0, is_enabled: true })).error, null);
  assert.equal((await db.from('ai_provider_keys').insert(keyIds.map((id, index) => ({ id, provider_id: providerId, label: `页面验收-${index + 1}`, api_key: 'local-only-fixture', priority: 55, is_enabled: true })))).error, null);
  assert.equal((await db.from('ai_provider_key_models').insert(modelIds.flatMap((model_id) => keyIds.map((key_id) => ({ key_id, model_id, is_enabled: true, global_is_enabled: true }))))).error, null);
  const page = await browser.newPage();
  page.on('pageerror', (error) => pageErrors.push(error.message));
  page.on('response', async (response) => { if (response.url().endsWith('/api/admin/ai-config') && response.request().method() === 'POST') console.log('mutation status', response.status(), response.ok() ? 'ok' : (await response.json()).error); });
  await page.goto(`${baseUrl}/login`);
  await page.getByLabel('邮箱', { exact: true }).fill(env.DYDATA_E2E_OWNER_EMAIL);
  await page.getByLabel('密码', { exact: true }).fill(env.DYDATA_E2E_OWNER_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL((url) => !url.pathname.includes('/login'));
  await page.goto(`${baseUrl}/admin/ai-config`);
  const card = page.locator(`[data-model-id="${modelIds[0]}"]`);
  const other = page.locator(`[data-model-id="${modelIds[1]}"]`);
  await card.waitFor();
  const order = (target) => target.locator('[data-key-id]').evaluateAll((rows) => rows.map((row) => row.dataset.keyId));
  const before = await order(card);
  const otherBefore = await order(other);
  await card.locator(`[data-key-id="${before[0]}"]`).hover();
  const swapped = page.waitForResponse((response) => response.url().endsWith('/api/admin/ai-config') && response.request().method() === 'POST');
  await card.locator(`[data-key-id="${before[0]}"]`).getByTitle('降低优先级（下移）').click();
  assert.equal((await swapped).status(), 200);
  await expect.poll(() => order(card)).toEqual([before[1], before[0], before[2]]);
  assert.deepEqual(await order(other), otherBefore);
  await card.locator(`[data-key-id="${before[0]}"]`).getByTitle('提高优先级（上移）').click();
  await expect.poll(() => order(card)).toEqual(before);
  await page.reload();
  await card.waitFor(); assert.deepEqual(await order(card), before);
  const sleep = await page.request.post(`${baseUrl}/api/admin/ai-config`, { data: { action: 'sleep_key', data: { key_id: keyIds[0] } } });
  assert.equal(sleep.status(), 200);
  const bundle = await sleep.json();
  const family = bundle.availability.modelFamilies.find((family) => family.modelId === modelIds[0]);
  assert.equal(family.identityCounts.sleeping, 1); assert.equal(family.schedulableChannelCount, 2);
  assert.equal(Object.values(family.identityCounts).reduce((sum, value) => sum + value, 0), 3);
  assert.equal((await page.request.post(`${baseUrl}/api/admin/ai-config`, { data: { action: 'resume_key', data: { key_id: keyIds[0] } } })).status(), 200);
  assert.deepEqual(pageErrors, []);
  console.log('PASS: owner login, actual page adjacent swap/reverse/reload, model isolation, authenticated sleep/resume, identity counts.');
} finally {
  assert.equal((await db.from('ai_providers').delete().eq('id', providerId)).error, null);
  assert.equal((await db.from('ai_provider_keys').select('id').in('id', keyIds)).data?.length, 0);
  await browser.close();
}
