export function matchTopicGroup(groups: TopicGroupMatchOption[], title: string, hook: string) {
  const haystack = `${title} ${hook}`.toLowerCase();
  let best: { groupId: string; score: number } | null = null;

  for (const group of groups) {
    const keywords = [group.name, ...(GROUP_KEYWORDS[group.name] ?? [])];
    const score = keywords.reduce(
      (total, keyword) => total + (haystack.includes(keyword.toLowerCase()) ? 1 : 0),
      0,
    );
    if (score > 0 && (!best || score > best.score)) best = { groupId: group.id, score };
  }

  return best?.groupId ?? null;
}
